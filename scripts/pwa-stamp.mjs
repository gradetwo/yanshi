// **∴ 本文件的职责 ✗**：**一个前缀 ＋ 一个值 ⇒ 把所有**该前缀**的戳换成那个值**✓**
//   · **全局**（**一处不漏 ✗ ⇒ 多个 occurrence 必须一起换 ✓**）
//   · **宽字符类**（**git 式／纯数字／占位符 `__BUILD_ID__` 都能吃 ✓**）
//   · **幂等**（**对同一个值再跑一次 ⇒ 结果不变 ✓**）
//   · **自愈**（**旧版本截脏出来的尾巴**`…irty-…` **会被整串吃掉**✓ ⇒ **∴ 再发布一次就干净 ✓**）
export const STAMP_TOKEN = "[A-Za-z0-9_-]+";
export const STAMP_PREFIXES = ["yanshi-shell", "yanshi-online"];

export function stampRegExp(prefix) {
  return new RegExp(`${prefix}-${STAMP_TOKEN}`, "g");
}

export function setStamp(text, prefix, value) {
  return text.replace(stampRegExp(prefix), `${prefix}-${value}`);
}
