use yanshi_render::buffer::Buffer;

/// **∴ 造一个 1×1 的缓冲**✗（**∴ 逐像素**路径**与之无关 ✓）** ✓✓
fn one_pixel(pixel: [f32; 4]) -> Buffer {
    let mut buffer = Buffer::new(0, 0, 1, 1);
    buffer.set_pixel(0, 0, pixel);
    buffer
}

/// **★ 黄金向量 ✗ ★**：**每条都写明**为什么这个期望值是对的 ✓**，
///   **而**不是"**从实现抄一个数 ✓" ✓。
#[test]
fn quantization_matches_hand_checked_golden_bytes() {
    // **①** 不透明白（**红通道满 ✓）⇒ 线性 1.0 编码后仍是 1.0 ⇒ 255 ✓
    assert_eq!(
        one_pixel([1.0, 0.0, 0.0, 1.0]).to_rgba8_quantized(None),
        vec![255, 0, 0, 255],
        "**满值红**必须编码成 255 ✗（**编码表在 1.0 处必须给 1.0 ✓）"
    );
    // **②** 全透明 ⇒ 四个通道都必须是 0 ✓
    assert_eq!(
        one_pixel([0.0, 0.0, 0.0, 0.0]).to_rgba8_quantized(None),
        vec![0, 0, 0, 0],
        "**全透明**必须是全 0 ✗（**不许留下预乘残值 ✓）"
    );
    // **③** 线性 0.5 ⇒ sRGB ≈ 0.7354 ⇒ 188 ✓（**手算：**1.055·0.5^(1/2.4)−0.055 ✓）
    assert_eq!(
        one_pixel([0.5, 0.5, 0.5, 1.0]).to_rgba8_quantized(None),
        vec![188, 188, 188, 255],
        "**线性 0.5** 必须编码成 188 ✗（**手算 0.7354 × 255 ≈ 188 ✓）"
    );
    // **★ ④ f16 往返的守门用例 ✗ ★**：
    //   **∴ 实测 ✗**：**同一输入**若**跳过 f16** ⇒ **189** ✓
    //     ⇒ **∴ 而**经 f16 往返 ⇒ **188** ✓（**f16 = 0.505859375 ✓）
    //   **∴ 所以**：**本断言红了**就说明**量化路径**少了一步 ✓
    assert_eq!(
        one_pixel([0.505_981_86, 0.505_981_86, 0.505_981_86, 1.0]).to_rgba8_quantized(None),
        vec![188, 188, 188, 255],
        "**必须发生 f16 往返** ✗：**跳过它**会把这里变成 189（**实测 ✓）\
         ⇒ **∴ 本用例**就是**SIMD／改写路径**的门 ✓"
    );
    // **⑤** 半透明灰（**α = 0.5 ✓）over 不透明白 ✗**：
    //   **∴ 公式（**读码核对 ✓）**：`out = pixel_premul + bg · (1 − α)`**✗
    //     ⇒ **∴ 手算 ✗**：**0.5 ＋ 1.0 × 0.5 = 1.0** ✓ ⇒ **∴ sRGB(1.0) ⇒ 255 ✓**** ✓✓
    //   **∴ 备注（**我自己的教训 ✓）**：**我**第一版注释**把 α 当成未预乘**✗
    //     ⇒ **∴ 算出 226** ✗（**错的 ✓）⇒ **∴ 而**实现给的 255 **才是对的** ✓
    //       ⇒ **★ 教训：**注释里的手算**必须**读码核对 ✓ ★**** ✓✓
    assert_eq!(
        one_pixel([0.5, 0.5, 0.5, 0.5]).to_rgba8_quantized(Some([255, 255, 255, 255])),
        vec![255, 255, 255, 255],
        "**半透明灰 over 不透明白** ✗：**0.5 + 1.0×0.5 = 1.0 ⇒ 255 ✓"
    );
}
